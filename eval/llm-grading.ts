import Anthropic from '@anthropic-ai/sdk'

const MODEL = 'claude-sonnet-5'

export interface QualityGrade {
  score: number
  reasoning: string
}

const QUALITY_SCHEMA = {
  type: 'object',
  properties: {
    score: { type: 'integer' },
    reasoning: { type: 'string' },
  },
  required: ['score', 'reasoning'],
  additionalProperties: false,
} as const

// Distinct from lib/llm.ts::gradeGroundedness — groundedness asks "is every
// claim actually supported by the excerpts," this asks "is it a GOOD answer
// to what was asked" (completeness, clarity, per-guest attribution when
// multiple perspectives are present). An answer can be perfectly grounded
// and still be a poor answer (rambling, partial, blending guest voices).
function buildQualityPrompt(question: string, answer: string): string {
  return `You are evaluating the QUALITY of an answer generated by a podcast Q&A tool — not whether it's grounded in the source transcripts (that's graded separately), but whether it's actually a GOOD answer to the question that was asked.

Question: ${question}

Answer:
${answer}

Score 0-100 based on:
- Does it directly and completely answer what was asked, rather than a tangent or a partial answer?
- Is it clearly written and well-organized — synthesized into a real answer, not just a pile of quotes with no connecting explanation?
- If multiple guests are cited, are their perspectives clearly attributed and distinguished, not blended into one voice or implying false consensus?

100 = an excellent, complete, clear answer to exactly what was asked. 0 = does not answer the question, or is confusing/unusable.`
}

export async function gradeAnswerQuality(question: string, answer: string): Promise<QualityGrade> {
  const client = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY })

  // Adaptive thinking is on by default when `thinking` is omitted on Sonnet
  // 5 — disabled here for the same reason as scripts/generate-golden-set.ts:
  // a short structured-output grading task doesn't need it, and the
  // invisible reasoning tokens risk truncating the JSON output.
  const response = await client.messages.create({
    model: MODEL,
    max_tokens: 300,
    thinking: { type: 'disabled' },
    output_config: { format: { type: 'json_schema', schema: QUALITY_SCHEMA } },
    messages: [{ role: 'user', content: buildQualityPrompt(question, answer) }],
  })

  const textBlock = response.content.find((b) => b.type === 'text')
  if (!textBlock || textBlock.type !== 'text') throw new Error('no text block in response')
  const parsed = JSON.parse(textBlock.text) as QualityGrade
  return { score: Math.max(0, Math.min(100, Math.round(parsed.score))), reasoning: parsed.reasoning }
}
